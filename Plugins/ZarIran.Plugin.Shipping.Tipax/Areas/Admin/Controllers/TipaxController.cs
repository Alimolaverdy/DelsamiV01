        public async Task<IActionResult> Configure()
        {

            if (!await _permissionService.AuthorizeAsync(StandardPermissionProvider.ManagePlugins))
                return Content("Access denied");

            var tipaxSettings = await _settingService.LoadSettingAsync<TipaxSettings>();

            var configurationModel = new ConfigurationModel
            {
                ShippingMethodId = tipaxSettings.ShippingMethodId,
                BaseUrl = tipaxSettings.BaseUrl,
                ApiKey = tipaxSettings.ApiKey,
                Username = tipaxSettings.Username,
                Password = tipaxSettings.Password,
                IsUnusual = tipaxSettings.IsUnusual,
                DistributionType = tipaxSettings.DistributionType,
                PackageContent = tipaxSettings.PackageContent,
                Packing = tipaxSettings.Packing,
                PackType = tipaxSettings.PackType,
                PaymentType = tipaxSettings.PaymentType,
                PickupType = tipaxSettings.PickupType,
                ServiceType = tipaxSettings.ServiceType,
                TimeoutSeconds = tipaxSettings.TimeoutSeconds,
                Multiplier = tipaxSettings.Multiplier,
            };


            foreach (var sm in await _shippingService.GetAllShippingMethodsAsync())
                configurationModel.AvailableShippingMethods.Add(new SelectListItem { Text = sm.Name, Value = sm.Id.ToString() });

            return View($"~/Plugins/ZarIran.Shipping.Tipax/Areas/Admin/Views/Tipax/Configure.cshtml", configurationModel);
        }

        [HttpPost]
        public async Task<IActionResult> Configure(ConfigurationModel model)
        {
            if (!await _permissionService.AuthorizeAsync(StandardPermissionProvider.ManagePlugins))
                return Content("Access denied");

            if (ModelState.IsValid)
            {
                var tipaxSettings = await _settingService.LoadSettingAsync<TipaxSettings>();

                tipaxSettings.ShippingMethodId = model.ShippingMethodId;
                tipaxSettings.BaseUrl = model.BaseUrl;
                tipaxSettings.ApiKey = model.ApiKey;
                tipaxSettings.Username = model.Username;
                tipaxSettings.Password = model.Password;
                tipaxSettings.IsUnusual = model.IsUnusual;
                tipaxSettings.DistributionType = model.DistributionType;
                tipaxSettings.PackageContent = model.PackageContent;
                tipaxSettings.Packing = model.Packing;
                tipaxSettings.PackType = model.PackType;
                tipaxSettings.PaymentType = model.PaymentType;
                tipaxSettings.PickupType = model.PickupType;
                tipaxSettings.ServiceType = model.ServiceType;
                tipaxSettings.TimeoutSeconds = model.TimeoutSeconds;
                tipaxSettings.Multiplier = model.Multiplier;

                _settingService.SaveSetting(tipaxSettings);

                _notificationService.SuccessNotification(await _localizationService.GetResourceAsync("Admin.Configuration.Updated"));

                return RedirectToAction("Configure");
            }

            _notificationService.ErrorNotification(await _localizationService.GetResourceAsync("ZarIran.Plugin.Settings.Error"));

            return View($"~/Plugins/ZarIran.Shipping.Tipax/Areas/Admin/Views/Tipax/Configure.cshtml", model);
        }

